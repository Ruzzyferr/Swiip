export interface PorsiyonTanimi {
  id: string;
  ad: string;
  gram: number;
}

export interface BesinTohumu {
  name_tr: string;
  /** İngilizce görünen ad. Zorunlu: uygulama 175 ülkede ve arama bu alanda da yapılıyor. */
  name_en: string;
  per_100g: {
    kalori: number;
    protein_g: number;
    yag_g: number;
    karbonhidrat_g: number;
    lif_g: number;
  };
  portions: PorsiyonTanimi[];
  source: 'turkomp' | 'openfoodfacts' | 'bizim' | 'kullanici' | 'zincir';
  verified: boolean;
}

/** Türkiye'de fiilen kullanılan ev ölçüleri. Gram tek başına kimseye bir şey ifade etmiyor. */
export const EV_OLCULERI = {
  kase: (gram: number): PorsiyonTanimi => ({ id: 'kase', ad: '1 kase', gram }),
  tabak: (gram: number): PorsiyonTanimi => ({ id: 'tabak', ad: '1 tabak', gram }),
  kepce: (gram: number): PorsiyonTanimi => ({ id: 'kepce', ad: '1 kepçe', gram }),
  yemekKasigi: (gram: number): PorsiyonTanimi => ({
    id: 'yemek_kasigi',
    ad: '1 yemek kaşığı',
    gram,
  }),
  cayKasigi: (gram: number): PorsiyonTanimi => ({ id: 'cay_kasigi', ad: '1 çay kaşığı', gram }),
  dilim: (gram: number): PorsiyonTanimi => ({ id: 'dilim', ad: '1 dilim', gram }),
  avuc: (gram: number): PorsiyonTanimi => ({ id: 'avuc', ad: '1 avuç', gram }),
  adet: (gram: number): PorsiyonTanimi => ({ id: 'adet', ad: '1 adet', gram }),
  bardak: (gram: number): PorsiyonTanimi => ({ id: 'bardak', ad: '1 su bardağı', gram }),
  porsiyon: (gram: number): PorsiyonTanimi => ({ id: 'porsiyon', ad: '1 porsiyon', gram }),
} as const;

